export function getActiveBuiltInPageLogicGraphs(
  project: FolioProject,
  pageId: string,
): LogicGraph[] {
  return getApplicableGraphsForPage(project, pageId).filter((graph) =>
    graph.nodes.some((node) => isBuiltInLogicNodeType(node.type)),
  );
}

function graphsUseStorage(graphs: LogicGraph[]): boolean {
  return graphs.some(
    (graph) =>
      (graph.variables ?? []).some((variable) => variable.persist === 'local' || variable.persist === 'session')
      || graph.nodes.some((node) => {
        if (node.type.startsWith('storage.')) return true;
        if (node.type === 'source.context') {
          const kind = String(node.data?.contextKind ?? node.data?.contextType ?? '');
          return kind === 'storage';
        }
        if (node.type === 'action.system-form') {
          const act = String(node.data?.action ?? '');
          return act === 'storage' || act.startsWith('storage.') || act.startsWith('storage-');
        }
        return false;
      }),
  );
}

function graphsUseComputed(graphs: LogicGraph[]): boolean {
  return graphs.some((graph) =>
    (graph.variables ?? []).some(
      (variable) =>
        Boolean(variable.computed)
        && typeof variable.computedExpression === 'string'
        && variable.computedExpression.trim().length > 0,
    ),
  );
}

function graphsUseLiveHttp(graphs: LogicGraph[]): boolean {
  return graphs.some((graph) =>
    graph.nodes.some(
      (node) =>
        (node.type === 'network.http' || node.type === 'source.external')
        && node.data?.executionMode === 'live',
    ),
  );
}


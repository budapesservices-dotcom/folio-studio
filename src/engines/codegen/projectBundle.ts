/**
 * Safely minifies SVG asset bytes by stripping XML comments, editor `<metadata>`,
 * and redundant inter-tag whitespace while preserving `<svg>`, `<title>`, `<path>`,
 * and styles verbatim. Returns original bytes unchanged if not valid SVG or not smaller.
 */
export function optimizeSvgBytes(rawBytes: Uint8Array): { bytes: Uint8Array; savedBytes: number } {
  try {
    const text = new TextDecoder('utf-8', { fatal: false }).decode(rawBytes);
    if (!/<svg[\s>]/i.test(text)) {
      return { bytes: rawBytes, savedBytes: 0 };
    }
    const minified = text
      .replace(/<!--[\s\S]*?-->/g, '')
      .replace(/<metadata\b[^>]*>[\s\S]*?<\/metadata>/gi, '')
      .replace(/>\s+</g, '><')
      .replace(/\s{2,}/g, ' ')
      .trim();
    if (!/<svg[\s>]/i.test(minified)) {
      return { bytes: rawBytes, savedBytes: 0 };
    }
    const encoded = new TextEncoder().encode(minified);
    if (encoded.byteLength < rawBytes.byteLength) {
      return {
        bytes: encoded,
        savedBytes: rawBytes.byteLength - encoded.byteLength,
      };
    }
  } catch {
    // Fall back to original bytes safely
  }
  return { bytes: rawBytes, savedBytes: 0 };
}

/**
 * Computes a deterministic 64-bit FNV-1a hex fingerprint for binary asset deduplication.
 */
function computeBinaryFingerprint(bytes: Uint8Array): string {
  let h1 = 0x811c9dc5;
  let h2 = 0x9e3779b9;
  for (let i = 0; i < bytes.length; i += 1) {
    const b = bytes[i];
    h1 ^= b;
    h1 = Math.imul(h1, 0x01000193);
    h2 ^= b ^ (i & 0xff);
    h2 = Math.imul(h2, 0x85ebca6b);
  }
  return `${bytes.length}:${(h1 >>> 0).toString(16).padStart(8, '0')}${(h2 >>> 0).toString(16).padStart(8, '0')}`;
}


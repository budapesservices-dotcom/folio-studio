/**
 * Compiles the full Folio project (all applications, pages, design tokens, components,
 * Shape Morph runtimes, and preserved Custom/Extension modules) and packages it into a
 * deploy-ready, asset-optimized ZIP archive pre-configured for Cloudflare Pages,
 * Netlify, and GitHub Pages.
 */
export function buildCompiledProjectBundle(
  inputProject: FolioProject,
  options: {
    target: CodeOutputTarget;
    pageId?: string;
    themeId?: string;
  },
): CompiledProjectBundle {
  const project = sanitizeProjectNetworkSecrets(inputProject);
  const compiled = compileFolioProject(project, {
    target: options.target,
    pageId: options.pageId,
    themeId: options.themeId,
    includeAllPages: true,
  });

  const activePage =
    project.pages.find((p) => p.id === compiled.activePageId) ?? getActivePage(project);
  const routeTable = buildMultiAppRouteTable(project);
  const projectSlug = toKebabCase(project.metadata.name, 'folio-project').slice(0, 48);
  const scaffold = options.target === 'react'
    ? buildReactScaffoldEntries(project, projectSlug, routeTable.manifestJson)
    : buildHtmlCssScaffoldEntries(project, activePage, routeTable.routes, routeTable.manifestJson);

  const entryMap = new Map<string, ZipArchiveEntry>();
  for (const item of scaffold) {
    entryMap.set(item.path, item);
  }
  for (const file of compiled.files) {
    // Compiled files & user modules always take precedence over scaffold placeholders
    entryMap.set(file.path, { path: file.path, content: file.content });
  }

  // Asset optimization: safe SVG minification + deterministic content-hash deduplication
  let assetCount = 0;
  let optimizedSvgCount = 0;
  let deduplicatedAssetCount = 0;
  let savedBytes = 0;

  const canonicalBundlePathByHash = new Map<string, string>();
  const pathRewrites = new Map<string, string>();

  for (const asset of project.assets) {
    const rawBytes = extractAssetBinaryBytesSync(asset);
    if (!rawBytes) continue;
    assetCount += 1;

    let finalBytes = rawBytes;
    const isSvg =
      asset.mimeType.toLowerCase() === 'image/svg+xml' ||
      asset.name.toLowerCase().endsWith('.svg');
    if (isSvg) {
      const optimized = optimizeSvgBytes(rawBytes);
      if (optimized.savedBytes > 0) {
        finalBytes = optimized.bytes;
        optimizedSvgCount += 1;
        savedBytes += optimized.savedBytes;
      }
    }

    const bundlePath = getAssetBundlePath(asset);
    const dedupKey = `${asset.mimeType.toLowerCase()}|${computeBinaryFingerprint(finalBytes)}`;
    const existingBundlePath = canonicalBundlePathByHash.get(dedupKey);
    if (existingBundlePath && existingBundlePath !== bundlePath) {
      deduplicatedAssetCount += 1;
      savedBytes += finalBytes.byteLength;
      pathRewrites.set(bundlePath, existingBundlePath);
      continue;
    }

    canonicalBundlePathByHash.set(dedupKey, bundlePath);
    const zipPath = options.target === 'react' ? `public/${bundlePath}` : bundlePath;
    entryMap.set(zipPath, { path: zipPath, content: finalBytes });
  }

  // Rewrite references to deduplicated asset paths cleanly across compiled text entries
  if (pathRewrites.size > 0) {
    for (const [entryPath, entry] of entryMap.entries()) {
      if (typeof entry.content !== 'string') continue;
      let updated = entry.content;
      for (const [duplicatePath, canonicalPath] of pathRewrites.entries()) {
        if (updated.includes(duplicatePath)) {
          updated = updated.split(duplicatePath).join(canonicalPath);
        }
      }
      if (updated !== entry.content) {
        entryMap.set(entryPath, { path: entryPath, content: updated });
      }
    }
  }

  const entries = Array.from(entryMap.values());
  const zipBytes = buildZipArchive(entries);
  const targetSuffix = options.target === 'react' ? 'react-ts' : 'html-css';

  return {
    fileName: `${projectSlug}-${targetSuffix}.zip`,
    target: options.target,
    entries,
    zipBytes,
    optimization: {
      assetCount,
      optimizedSvgCount,
      deduplicatedAssetCount,
      savedBytes,
      applicationCount: routeTable.applicationCount,
      pageCount: project.pages.length,
      deployTargets: ['cloudflare-pages', 'netlify', 'github-pages'],
    },
  };
}

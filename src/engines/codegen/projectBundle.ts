function buildHtmlGitHubPages404Html(
  projectName: string,
  routes: readonly NormalizedRouteEntry[],
  fallbackHtmlPath: string,
): string {
  const routeMap: Record<string, string> = {};
  for (const entry of routes) {
    routeMap[entry.route] = entry.htmlPath;
  }
  const serializedRoutes = JSON.stringify(routeMap).replace(/</g, '\\u003c');
  return [
    '<!doctype html>',
    '<html lang="en">',
    '  <head>',
    '    <meta charset="UTF-8" />',
    '    <meta name="viewport" content="width=device-width, initial-scale=1.0" />',
    `    <title>${escapeHtml(projectName)}</title>`,
    '    <script>',
    '      (function(){',
    `        var ROUTES=${serializedRoutes};`,
    `        var FALLBACK=${JSON.stringify(fallbackHtmlPath)};`,
    '        var l=window.location;',
    '        var segs=l.pathname.split("/").filter(Boolean);',
    '        var isProjectSite=l.hostname.endsWith(".github.io")&&segs.length>0;',
    '        var base=isProjectSite?"/"+segs[0]+"/":"/";',
    '        var rel=isProjectSite?"/"+segs.slice(1).join("/"):l.pathname;',
    '        var norm=rel.length>1?rel.replace(/\\/+$/,""):"/";',
    '        var dest=ROUTES[norm]||FALLBACK;',
    '        l.replace(base+dest);',
    '      })();',
    '    </script>',
    '  </head>',
    '  <body>',
    `    <p>Redirecting to <a href="${escapeAttr(fallbackHtmlPath)}">${escapeHtml(projectName)}</a>…</p>`,
    '  </body>',
    '</html>',
    '',
  ].join('\n');
}


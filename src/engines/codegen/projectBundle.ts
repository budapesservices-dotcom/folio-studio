function buildHtmlNetlifyToml(
  routes: readonly NormalizedRouteEntry[],
  fallbackHtmlPath: string,
): string {
  const lines: string[] = [
    '# Generated by FOLIO Studio — Free static deploy config for Netlify (Drag & Drop or Git)',
    '[build]',
    '  publish = "."',
    '',
  ];
  for (const entry of routes) {
    lines.push('[[redirects]]');
    lines.push(`  from = ${JSON.stringify(entry.route)}`);
    lines.push(`  to = ${JSON.stringify(`/${entry.htmlPath}`)}`);
    lines.push('  status = 200');
    lines.push('');
    if (entry.route !== '/') {
      lines.push('[[redirects]]');
      lines.push(`  from = ${JSON.stringify(`${entry.route}/`)}`);
      lines.push(`  to = ${JSON.stringify(`/${entry.htmlPath}`)}`);
      lines.push('  status = 200');
      lines.push('');
    }
  }
  lines.push('[[redirects]]');
  lines.push('  from = "/*"');
  lines.push(`  to = ${JSON.stringify(`/${fallbackHtmlPath}`)}`);
  lines.push('  status = 200');
  lines.push('');
  lines.push('[[headers]]');
  lines.push('  for = "/*"');
  lines.push('  [headers.values]');
  lines.push('    X-Content-Type-Options = "nosniff"');
  lines.push('    Referrer-Policy = "strict-origin-when-cross-origin"');
  lines.push('    X-Frame-Options = "SAMEORIGIN"');
  lines.push('');
  lines.push('[[headers]]');
  lines.push('  for = "/assets/*"');
  lines.push('  [headers.values]');
  lines.push('    Cache-Control = "public, max-age=31536000, immutable"');
  lines.push('');
  return lines.join('\n');
}

function buildHtmlCloudflareRedirects(
  routes: readonly NormalizedRouteEntry[],
  fallbackHtmlPath: string,
): string {
  const lines: string[] = [
    '# Generated by FOLIO Studio — Multi-application routes for Cloudflare Pages',
  ];
  for (const entry of routes) {
    lines.push(`${entry.route} /${entry.htmlPath} 200`);
    if (entry.route !== '/') {
      lines.push(`${entry.route}/ /${entry.htmlPath} 200`);
    }
  }
  lines.push(`/* /${fallbackHtmlPath} 200`);
  lines.push('');
  return lines.join('\n');
}


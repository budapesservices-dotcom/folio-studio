interface NormalizedRouteEntry {
  readonly appId: string;
  readonly appName: string;
  readonly appSlug: string;
  readonly appBasePath: string;
  readonly pageId: string;
  readonly pageName: string;
  readonly route: string;
  readonly htmlPath: string;
}

function normalizeStaticRoute(route: string): string {
  const trimmed = route.trim().split('?')[0].split('#')[0] || '/';
  const withLeading = trimmed.startsWith('/') ? trimmed : `/${trimmed}`;
  return withLeading.length > 1 ? withLeading.replace(/\/+$/, '') : '/';
}

function buildMultiAppRouteTable(project: FolioProject): {
  readonly manifestJson: string;
  readonly routes: readonly NormalizedRouteEntry[];
  readonly applicationCount: number;
} {
  const applications = getProjectApplications(project);
  const routes: NormalizedRouteEntry[] = [];
  const seenRoutes = new Set<string>();

  const appsManifest = applications.map((app) => {
    const appPages = project.pages.filter((p) => getPageApplicationId(project, p) === app.id);
    return {
      id: app.id,
      name: app.name,
      slug: app.slug,
      basePath: normalizeStaticRoute(app.basePath),
      pages: appPages.map((page) => {
        const slug = toPageFileSlug(page.route, page.name);
        const route = normalizeStaticRoute(page.route);
        const htmlPath = `pages/${slug}.html`;
        if (!seenRoutes.has(route)) {
          seenRoutes.add(route);
          routes.push({
            appId: app.id,
            appName: app.name,
            appSlug: app.slug,
            appBasePath: normalizeStaticRoute(app.basePath),
            pageId: page.id,
            pageName: page.name,
            route,
            htmlPath,
          });
        }
        return {
          id: page.id,
          name: page.name,
          route,
          htmlFile: htmlPath,
        };
      }),
    };
  });

  const manifestJson = JSON.stringify(
    {
      schemaVersion: 1,
      projectName: project.metadata.name,
      deployTargets: ['cloudflare-pages', 'netlify', 'github-pages'],
      applications: appsManifest,
      routes: routes.map((r) => ({
        appId: r.appId,
        appSlug: r.appSlug,
        pageId: r.pageId,
        pageName: r.pageName,
        route: r.route,
        htmlFile: r.htmlPath,
      })),
    },
    null,
    2,
  );

  return {
    manifestJson: `${manifestJson}\n`,
    routes,
    applicationCount: applications.length,
  };
}


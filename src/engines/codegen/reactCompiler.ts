import { getActivePage } from '../../core/document/project';
import type {
  ComponentDefinition,
  DesignNode,
  FolioPage,
  FolioProject,
} from '../../core/document/types';
import { resolveSemanticTag } from './htmlCssCompiler';
import {
  sanitizeHref,
  toCamelCase,
  toCssClassName,
  toPageFileSlug,
  toPascalCase,
} from './sanitize';
import type { CodeMappingEntry, CompiledCodeFile } from './types';

function escapeJsxText(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\{/g, '&#123;')
    .replace(/\}/g, '&#125;');
}

function escapeTsString(value: string): string {
  return JSON.stringify(value);
}

function buildComponentFile(component: ComponentDefinition): CompiledCodeFile {
  const componentName = toPascalCase(component.name, 'FolioComponent');
  const lines: string[] = [
    '// Generated by FOLIO Code Engine — Component Contract',
    '// Variants and Slots compile to typed React + TypeScript props.',
    "import React from 'react';",
    '',
  ];

  const propLines: string[] = [];
  const destructuredProps: string[] = [];

  for (const axis of component.variants ?? []) {
    const propName = toCamelCase(axis.name, 'variant');
    const unionType = axis.options.map((opt) => escapeTsString(opt.label)).join(' | ') || 'string';
    const defaultOpt = axis.options.find((opt) => opt.id === axis.defaultOptionId) ?? axis.options[0];
    propLines.push(`  ${propName}?: ${unionType};`);
    destructuredProps.push(
      defaultOpt
        ? `${propName} = ${escapeTsString(defaultOpt.label)}`
        : propName,
    );
  }

  for (const slot of component.slots ?? []) {
    const slotProp = toCamelCase(slot.name, 'slot');
    propLines.push(`  ${slotProp}?: React.ReactNode;`);
    destructuredProps.push(
      slot.defaultText !== undefined
        ? `${slotProp} = ${escapeTsString(slot.defaultText)}`
        : slotProp,
    );
  }

  propLines.push('  className?: string;');
  destructuredProps.push('className');

  lines.push(`export interface ${componentName}Props {`);
  lines.push(...propLines);
  lines.push('}');
  lines.push('');

  const slotByTargetId = new Map(
    (component.slots ?? []).map((slot) => [slot.targetNodeId, toCamelCase(slot.name, 'slot')]),
  );

  lines.push(`export function ${componentName}({`);
  for (const entry of destructuredProps) {
    lines.push(`  ${entry},`);
  }
  lines.push(`}: ${componentName}Props) {`);
  lines.push('  return (');
  lines.push(
    `    <div className={[${escapeTsString(`folio-comp-${toPageFileSlug('', component.name)}`)}, className].filter(Boolean).join(' ')} data-folio-component=${escapeTsString(component.id)}>`,
  );

  const mappings: CodeMappingEntry[] = [];
  for (const node of component.document.nodes) {
    if (!node.visible || node.onCanvas === false) continue;
    const tag = resolveSemanticTag(node);
    const cls = toCssClassName('fc', node.name, node.id);
    const slotProp = slotByTargetId.get(node.id);
    const startLine = lines.length + 1;

    if (slotProp) {
      lines.push(`      <${tag} className=${escapeTsString(cls)} data-folio-id=${escapeTsString(node.id)}>{${slotProp}}</${tag}>`);
    } else if (node.type === 'text') {
      lines.push(`      <${tag} className=${escapeTsString(cls)} data-folio-id=${escapeTsString(node.id)}>${escapeJsxText(node.text)}</${tag}>`);
    } else {
      lines.push(`      <${tag} className=${escapeTsString(cls)} data-folio-id=${escapeTsString(node.id)} />`);
    }

    mappings.push({
      nodeId: node.id,
      nodeName: node.name,
      componentId: component.id,
      category: 'generated',
      startLine,
      endLine: lines.length,
      selector: `.${cls}`,
    });
  }

  lines.push('    </div>');
  lines.push('  );');
  lines.push('}');
  lines.push('');

  return {
    id: `generated:react:component:${component.id}`,
    path: `src/components/${componentName}.tsx`,
    language: 'tsx',
    category: 'generated',
    readOnly: true,
    content: lines.join('\n'),
    componentId: component.id,
    description: `Typed React component generated from Master "${component.name}".`,
    mappings,
  };
}

function buildPageReactFile(
  project: FolioProject,
  page: FolioPage,
): CompiledCodeFile {
  const pageComponentName = `${toPascalCase(page.name, 'Page')}Page`;
  const slug = toPageFileSlug(page.route, page.name);
  const componentsById = new Map(project.components.map((c) => [c.id, c]));

  const usedComponents = new Set<string>();
  for (const node of page.document.nodes) {
    if (node.type === 'component-instance' && componentsById.has(node.componentId)) {
      usedComponents.add(node.componentId);
    }
  }

  const lines: string[] = [
    `// Mapped by FOLIO Code Engine — Page "${page.name}" (${page.route})`,
    "import React from 'react';",
    `import '../styles/${slug}.css';`,
  ];

  for (const compId of usedComponents) {
    const comp = componentsById.get(compId);
    if (!comp) continue;
    const compName = toPascalCase(comp.name, 'FolioComponent');
    lines.push(`import { ${compName} } from '../components/${compName}';`);
  }

  for (const mod of project.codeModules ?? []) {
    if (mod.language === 'css' && (!mod.targetPageId || mod.targetPageId === page.id)) {
      lines.push(`import '../${mod.path}';`);
    }
  }

  lines.push('');
  lines.push(`export function ${pageComponentName}() {`);
  lines.push('  return (');
  lines.push(`    <main className=${escapeTsString(`folio-page-${slug}`)} data-folio-page=${escapeTsString(page.id)}>`);

  const nodeById = new Map(page.document.nodes.map((node) => [node.id, node]));
  const childrenByParent = new Map<string, DesignNode[]>();
  const roots: DesignNode[] = [];
  for (const node of page.document.nodes) {
    if (node.onCanvas === false) continue;
    if (node.parentId && nodeById.has(node.parentId)) {
      const list = childrenByParent.get(node.parentId) ?? [];
      list.push(node);
      childrenByParent.set(node.parentId, list);
    } else {
      roots.push(node);
    }
  }

  const mappings: CodeMappingEntry[] = [];

  const emitJsx = (node: DesignNode, depth: number) => {
    const indent = '  '.repeat(depth);
    const cls = toCssClassName('f', node.name, node.id);
    const startLine = lines.length + 1;

    if (node.type === 'component-instance') {
      const comp = componentsById.get(node.componentId);
      if (comp) {
        const compName = toPascalCase(comp.name, 'FolioComponent');
        const props: string[] = [`className=${escapeTsString(cls)}`];
        for (const axis of comp.variants ?? []) {
          const chosenId = node.variantSelection?.[axis.id] ?? axis.defaultOptionId;
          const opt = axis.options.find((o) => o.id === chosenId);
          if (opt) {
            props.push(`${toCamelCase(axis.name, 'variant')}=${escapeTsString(opt.label)}`);
          }
        }
        for (const slot of comp.slots ?? []) {
          const assignment = node.slotAssignments?.[slot.id];
          if (assignment?.text !== undefined) {
            props.push(`${toCamelCase(slot.name, 'slot')}=${escapeTsString(assignment.text)}`);
          }
        }
        lines.push(`${indent}<${compName} ${props.join(' ')} />`);
        mappings.push({
          nodeId: node.id,
          nodeName: node.name,
          pageId: page.id,
          category: 'mapped',
          startLine,
          endLine: lines.length,
          selector: `.${cls}`,
        });
        return;
      }
    }

    const tag = resolveSemanticTag(node);
    const attrs: string[] = [
      `className=${escapeTsString(cls)}`,
      `data-folio-id=${escapeTsString(node.id)}`,
    ];
    if (node.ariaLabel?.trim()) {
      attrs.push(`aria-label=${escapeTsString(node.ariaLabel.trim())}`);
    }
    if (tag === 'a') {
      attrs.push(`href=${escapeTsString(sanitizeHref(node.href) ?? '#')}`);
    }
    if (tag === 'button') {
      attrs.push('type="button"');
    }

    if (node.type === 'text') {
      lines.push(`${indent}<${tag} ${attrs.join(' ')}>${escapeJsxText(node.text)}</${tag}>`);
    } else {
      const children = childrenByParent.get(node.id) ?? [];
      if (children.length === 0) {
        lines.push(`${indent}<${tag} ${attrs.join(' ')} />`);
      } else {
        lines.push(`${indent}<${tag} ${attrs.join(' ')}>`);
        for (const child of children) {
          emitJsx(child, depth + 1);
        }
        lines.push(`${indent}</${tag}>`);
      }
    }

    mappings.push({
      nodeId: node.id,
      nodeName: node.name,
      pageId: page.id,
      category: 'mapped',
      startLine,
      endLine: lines.length,
      selector: `.${cls}`,
    });
  };

  for (const root of roots) {
    emitJsx(root, 3);
  }

  lines.push('    </main>');
  lines.push('  );');
  lines.push('}');
  lines.push('');

  return {
    id: `mapped:react:page:${page.id}`,
    path: `src/pages/${pageComponentName}.tsx`,
    language: 'tsx',
    category: 'mapped',
    readOnly: false,
    content: lines.join('\n'),
    pageId: page.id,
    description: `React + TypeScript page mapped to Folio AST "${page.name}".`,
    mappings,
  };
}

function buildAppEntryFile(project: FolioProject, activePage: FolioPage): CompiledCodeFile {
  const lines: string[] = [
    '// Generated by FOLIO Code Engine — Application Entry',
    "import React from 'react';",
    "import './styles/tokens.css';",
  ];

  for (const page of project.pages) {
    const pageComp = `${toPascalCase(page.name, 'Page')}Page`;
    lines.push(`import { ${pageComp} } from './pages/${pageComp}';`);
  }

  lines.push('');
  lines.push('export function App({ route = ' + escapeTsString(activePage.route) + ' }: { route?: string }) {');
  lines.push('  switch (route) {');
  for (const page of project.pages) {
    const pageComp = `${toPascalCase(page.name, 'Page')}Page`;
    lines.push(`    case ${escapeTsString(page.route)}:`);
    lines.push(`      return <${pageComp} />;`);
  }
  const activeComp = `${toPascalCase(activePage.name, 'Page')}Page`;
  lines.push('    default:');
  lines.push(`      return <${activeComp} />;`);
  lines.push('  }');
  lines.push('}');
  lines.push('');

  return {
    id: 'generated:react:app',
    path: 'src/App.tsx',
    language: 'tsx',
    category: 'generated',
    readOnly: true,
    content: lines.join('\n'),
    description: 'Generated React application entry mapping Folio page routes.',
    mappings: [],
  };
}

export function compileReactProjectFiles(
  project: FolioProject,
  activePageId?: string,
): CompiledCodeFile[] {
  const activePage =
    (activePageId ? project.pages.find((p) => p.id === activePageId) : undefined) ??
    getActivePage(project);
  const files: CompiledCodeFile[] = [buildAppEntryFile(project, activePage)];

  for (const page of project.pages) {
    files.push(buildPageReactFile(project, page));
  }
  for (const component of project.components) {
    files.push(buildComponentFile(component));
  }
  return files;
}
